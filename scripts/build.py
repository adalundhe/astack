#!/usr/bin/env python3
"""Build astack's packages for Claude Code, Cursor and Codex from the source at the repository root.

Usage: python3 scripts/build.py [--check]

Writes harness/claude-code, harness/cursor and harness/codex. Cursor and Codex get prefixed names
(astack-go, astack-lead, astack-worker, ...) and the sentences in packaging/<tool>/replace.json. The build
fails when a sentence in replace.json is missing from the source, or when a Claude Code-only name is left in
their skills or agents. With --check, it builds into a temporary folder and fails if harness/ differs.
"""
import argparse
import json
import re
import shutil
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "harness"
PACKAGING = ROOT / "packaging"
DOCS = ("README.md", "LICENSE", "NOTICE.md")
RENAMED = ("go", "lead", "setup", "status", "review")
TOOLS = {
    "claude-code": {"prefixed": False, "invoke": "/astack:", "agent": "claude-code"},
    "cursor": {"prefixed": True, "invoke": "/", "agent": "cursor"},
    "codex": {"prefixed": True, "invoke": "$", "agent": "codex"},
}
MANIFESTS = {
    "claude-code": ".claude-plugin/plugin.json",
    "cursor": ".cursor-plugin/plugin.json",
    "codex": "plugin.json",
}
README = """# astack packages

Generated by `python3 scripts/build.py` from the source at the repository root. Don't edit these folders by hand.

- `claude-code/` is the Claude Code plugin, listed in `.claude-plugin/marketplace.json`.
- `cursor/` is the Cursor plugin, listed in `.cursor-plugin/marketplace.json`.
- `codex/` is the Codex plugin, listed in `.agents/plugins/marketplace.json`.
"""


class BuildError(Exception):
    pass


def split_front_matter(path, text):
    match = re.match(r"---\n(.*?)\n---\n", text, re.S)
    if not match:
        raise BuildError(f"{path} has no front matter")
    fields = {}
    for line in match.group(1).splitlines():
        key, _, value = line.partition(":")
        fields[key.strip()] = value.strip()
    return fields, text[match.end():]


def join_front_matter(fields, body):
    return "---\n" + "".join(f"{key}: {value}\n" for key, value in fields.items()) + "---\n" + body


def unquote(value):
    if len(value) >= 2 and value[0] == value[-1] == '"':
        return value[1:-1].replace('\\"', '"').replace("\\\\", "\\")
    return value


def skill_name(name, tool):
    return f"astack-{name}" if TOOLS[tool]["prefixed"] and name in RENAMED else name


class Translator:
    def __init__(self, tool):
        self.tool = tool
        self.table = {"replace": [], "forbid": []}
        if TOOLS[tool]["prefixed"]:
            self.table = json.loads((PACKAGING / tool / "replace.json").read_text())
        self.used = set()

    def __call__(self, text):
        if not TOOLS[self.tool]["prefixed"]:
            return text
        for source, target in self.table["replace"]:
            if source in text:
                text = text.replace(source, target)
                self.used.add(source)
        invoke = TOOLS[self.tool]["invoke"]
        text = re.sub(
            r"\$\{CLAUDE_SKILL_DIR\}/\.\./([a-z0-9-]+)/SKILL\.md",
            lambda match: f"../{skill_name(match.group(1), self.tool)}/SKILL.md",
            text,
        )
        text = text.replace("${CLAUDE_SKILL_DIR}/../", "../")
        text = re.sub(
            r"/astack:([a-z0-9-]+)\b",
            lambda match: f"{invoke}{skill_name(match.group(1), self.tool)}",
            text,
        )
        text = text.replace("astack:worker", "astack-worker")
        return text.replace("astack:reviewer", "astack-reviewer")

    def check(self, path, text):
        for token in self.table["forbid"]:
            if token in text:
                raise BuildError(f"{self.tool}: {path} still says {token!r}; add its sentence to replace.json")

    def check_all_used(self):
        for source, _ in self.table["replace"]:
            if source not in self.used:
                raise BuildError(f"{self.tool}: replace.json names a sentence the source no longer has: {source!r}")


def write(path, text, executable=False):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
    path.chmod(0o755 if executable else 0o644)


def build_skills(tool, out, translate):
    for skill in sorted(p for p in (ROOT / "skills").iterdir() if (p / "SKILL.md").is_file()):
        name = skill_name(skill.name, tool)
        for source in sorted(p for p in skill.rglob("*") if p.is_file()):
            target = out / "skills" / name / source.relative_to(skill)
            text = translate(source.read_text())
            if source.name == "SKILL.md":
                fields, body = split_front_matter(source, text)
                fields["name"] = name
                text = join_front_matter(fields, body)
            translate.check(target.relative_to(out), text)
            write(target, text)


def build_agents(tool, out, translate):
    for source in sorted((ROOT / "agents").glob("*.md")):
        text = translate(source.read_text())
        fields, body = split_front_matter(source, text)
        name = f"astack-{source.stem}" if TOOLS[tool]["prefixed"] else source.stem
        if tool == "claude-code":
            target, text = out / "agents" / source.name, text
        elif tool == "cursor":
            target = out / "agents" / f"{name}.md"
            text = join_front_matter({"name": name, "description": fields["description"], "is_background": "true"}, body)
        else:
            if "'''" in body:
                raise BuildError(f"{source} contains ''' and can't be a TOML literal string")
            description = unquote(fields["description"]).replace("\\", "\\\\").replace('"', '\\"')
            target = out / "agents" / f"{name}.toml"
            text = f'name = "{name}"\ndescription = "{description}"\ndeveloper_instructions = \'\'\'\n{body.strip()}\n\'\'\'\n'
        translate.check(target.relative_to(out), text)
        write(target, text)


def build_tool(tool, out):
    translate = Translator(tool)
    build_skills(tool, out, translate)
    build_agents(tool, out, translate)
    translate.check_all_used()
    for script in sorted((ROOT / "bin").iterdir()):
        write(out / "bin" / script.name, script.read_text(), executable=True)
    for source in sorted(p for p in (PACKAGING / tool).rglob("*") if p.is_file() and p.name != "replace.json"):
        write(out / source.relative_to(PACKAGING / tool), source.read_text())
    for doc in DOCS:
        write(out / doc, (ROOT / doc).read_text())
    if tool == "claude-code":
        for source in sorted(p for p in (ROOT / "evals").rglob("*") if p.is_file()):
            write(out / "evals" / source.relative_to(ROOT / "evals"), source.read_text(),
                  executable=bool(source.stat().st_mode & 0o111))


def build(out):
    versions = {tool: json.loads((PACKAGING / tool / path).read_text())["version"] for tool, path in MANIFESTS.items()}
    if len(set(versions.values())) != 1:
        raise BuildError(f"manifest versions differ: {versions}")
    for tool in TOOLS:
        build_tool(tool, out / tool)
    write(out / "README.md", README)


def tree(root):
    return {path.relative_to(root): (path.read_bytes(), bool(path.stat().st_mode & 0o111))
            for path in root.rglob("*") if path.is_file()}


def main():
    parser = argparse.ArgumentParser(description="Build astack's packages.")
    parser.add_argument("--check", action="store_true", help="fail if harness/ is not what the source builds")
    args = parser.parse_args()
    try:
        if args.check:
            with tempfile.TemporaryDirectory(prefix="astack-build-") as scratch:
                build(Path(scratch))
                built, committed = tree(Path(scratch)), tree(OUT) if OUT.is_dir() else {}
            stale = sorted(str(path) for path in built.keys() | committed.keys()
                           if built.get(path) != committed.get(path))
            if stale:
                print("harness/ is out of date; run python3 scripts/build.py. Differs: " + ", ".join(stale))
                return 1
            print("harness/ is up to date.")
            return 0
        if OUT.exists():
            shutil.rmtree(OUT)
        build(OUT)
        print(f"Built {', '.join(TOOLS)} in {OUT.relative_to(ROOT)}/.")
        return 0
    except BuildError as error:
        print(f"build failed: {error}")
        return 1


if __name__ == "__main__":
    sys.exit(main())
